import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { PassThrough } from 'node:stream';
import { waitForMcpStartup } from './test-process.mjs';
const processFixture = () => Object.assign(new EventEmitter(), { stderr: new PassThrough(), exitCode: null });
const child = processFixture();
let ready = false;
const wait = waitForMcpStartup(child).then(() => { ready = true; });
child.stderr.write('DOCS_MCP_API_KEY descontinuada: migre para DOCS_MCP_CREDENTIALS.\n');
await Promise.resolve();
assert.equal(ready, false, 'warning is not readiness or failure');
child.stderr.write('iHelp Docs MCP ouvindo na ');
child.stderr.write('porta 1234\n');
await wait;
assert.equal(child.listenerCount('exit'), 0);
const rejected = processFixture();
const exited = waitForMcpStartup(rejected, { expectExit: true });
rejected.stderr.write('Invalid configuration');
rejected.exitCode = 1;
rejected.emit('exit', 1, null);
assert.equal((await exited).exitCode, 1);
const premature = processFixture();
const prematureWait = assert.rejects(waitForMcpStartup(premature), /exited before readiness/);
premature.emit('exit', 1, null);
await prematureWait;
const unexpected = processFixture();
const unexpectedWait = assert.rejects(waitForMcpStartup(unexpected, { expectExit: true }), /started when configuration/);
unexpected.stderr.write('MCP ouvindo na porta 0');
await unexpectedWait;
const stalled = processFixture();
await assert.rejects(waitForMcpStartup(stalled, { timeoutMs: 1 }), /startup exceeded/);
assert.equal(stalled.stderr.listenerCount('data'), 0);
console.log('test-process: ok');
