import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { adoptMarkers } from './adotar-marcador-mcp.mjs';

const root = await mkdtemp(join(tmpdir(), 'm560-adopt-'));
const run = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
run('init', '-q');
run('config', 'user.name', 'Editor');
run('config', 'user.email', 'editor@example.test');
const dir = join(root, 'pilot/content/docs/docs');
await mkdir(dir, { recursive: true });
const normal = '---\ntitle: Exemplo\n---\n\nCorpo  \n\n## Título\n\nTexto.\n';
await writeFile(join(dir, 'normal.mdx'), normal);
await writeFile(join(dir, 'manual.mdx'), normal.replace('title: Exemplo', 'title: Exemplo\nmanual: true'));
await writeFile(join(dir, 'marked.mdx'), normal.replace('title: Exemplo', `title: Exemplo\nmcpGeneratedSha: ${'a'.repeat(40)}`));
run('add', '.'); run('commit', '-qm', 'pages');
const lastTouch = run('rev-parse', 'HEAD');
const first = await adoptMarkers(root);
assert.equal(first, 1);
const result = await readFile(join(dir, 'normal.mdx'), 'utf8');
assert.equal(result, normal.replace('---\n', `---\nmcpGeneratedSha: ${lastTouch}\n`));
assert.equal(result.slice(result.indexOf('---\n', 4) + 4), normal.slice(normal.indexOf('---\n', 4) + 4), 'corpo byte a byte');
assert.equal(await adoptMarkers(root), 0, 'idempotente');
assert.equal(await readFile(join(dir, 'manual.mdx'), 'utf8'), normal.replace('title: Exemplo', 'title: Exemplo\nmanual: true'));
assert.equal(await readFile(join(dir, 'marked.mdx'), 'utf8'), normal.replace('title: Exemplo', `title: Exemplo\nmcpGeneratedSha: ${'a'.repeat(40)}`));
console.log('adotar marcador MCP: ok');
