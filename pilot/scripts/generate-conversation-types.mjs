import { readFile, writeFile } from 'node:fs/promises';
import { z } from 'zod/v4';
import actions from '../architecture/product-actions.json' with { type: 'json' };
import guideIds from '../architecture/guide-ids.json' with { type: 'json' };
import { assistantReplySchema, assistantRequestSchema, guideSchema, productActionSchema } from '../architecture/conversation-v1.mjs';

const schemas = {
  GuideV1: z.toJSONSchema(guideSchema),
  AssistantRequestV1: z.toJSONSchema(assistantRequestSchema, { io: 'input' }),
  AssistantReplyV1: z.toJSONSchema(assistantReplySchema),
  ProductActionV1: z.toJSONSchema(productActionSchema),
};
const literalUnion = (values) => values.map((value) => JSON.stringify(value)).join(' | ');
function typeOf(schema, key = '') {
  if (schema.anyOf) return schema.anyOf.map((item) => typeOf(item)).join(' | ');
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return literalUnion(schema.enum);
  if (key === 'guideId') return 'GuideId';
  if (key === 'actionId') return 'ActionId';
  if (schema.type === 'array') return `Array<${typeOf(schema.items)}>`;
  if (schema.type === 'object') {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([name, child]) =>
      `  ${name}${required.has(name) ? '' : '?'}: ${typeOf(child, name)};`);
    return `{\n${fields.join('\n')}\n}`;
  }
  if (schema.type === 'string') return 'string';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'null') return 'null';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  throw new Error(`JSON Schema não suportado: ${JSON.stringify(schema)}`);
}
const typeSource = [
  '// Generated by scripts/generate-conversation-types.mjs. Do not edit.',
  `export type ActionId = ${literalUnion(Object.keys(actions))};`,
  `export type GuideId = ${literalUnion(guideIds)};`,
  ...Object.entries(schemas).map(([name, schema]) => `export type ${name} = ${typeOf(schema)};`),
  '',
].join('\n\n').trimEnd() + '\n';
const jsonSource = `${JSON.stringify({ schemaVersion: 1, schemas }, null, 2)}\n`;
for (const [path, source] of [
  [new URL('../lib/conversation-contract.generated.ts', import.meta.url), typeSource],
  [new URL('../architecture/conversation-v1.schema.json', import.meta.url), jsonSource],
]) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== source) throw new Error(`${path.pathname} desatualizado`);
  } else await writeFile(path, source);
}
